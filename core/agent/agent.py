from typing import List, Dict, Any, Tuple, Optional


class Agent:
    """
    Agent class that coordinates LLM calls and knowledge base operations.
    
    Serves as the main interface for:
    - Making LLM API calls with retry logic
    - Managing knowledge base operations (add/update/delete/retrieve)
    - Executing structured operations generated by KB builders
    """
    
    def __init__(self, llm, kb=None):
        """
        Initialize the agent.
        
        Args:
            llm: LLM instance for making API calls
            kb: Optional KnowledgeBase instance for memory operations
        """
        self.llm = llm
        self.kb = kb

    async def call_llm(
        self, 
        system_prompt: str, 
        user_prompt: str, 
        temperature: float = 0.0
    ) -> str:
        """
        Call the LLM with system and user prompts.
        
        Args:
            system_prompt: System-level instructions
            user_prompt: User query or task description
            temperature: Sampling temperature (0.0 = deterministic)
            
        Returns:
            LLM response as string
        """
        return await self.llm.call(system_prompt, user_prompt, temperature)
    
    async def add_memory(
        self, 
        key: Dict[str, Any], 
        value: Dict[str, Any]
    ) -> Tuple[bool, Optional[str]]:
        """
        Add a new memory entry to the knowledge base.
        
        Args:
            key: Memory key dictionary (used for retrieval)
            value: Memory value dictionary (additional information)
            
        Returns:
            Tuple of (success flag, memory ID or None)
            
        Raises:
            ValueError: If knowledge base is not available
        """
        if self.kb is None:
            raise ValueError("Knowledge base is not available")
        return await self.kb.add_memory(key, value)

    async def update_memory(
        self, 
        memory_id: str, 
        value: Dict[str, Any], 
        key: Dict[str, Any] = None
    ) -> bool:
        """
        Update an existing memory entry.
        
        Args:
            memory_id: Memory ID to update
            value: Values to update
            key: Optional new key (triggers embedding recalculation)
            
        Returns:
            Whether update was successful
            
        Raises:
            ValueError: If knowledge base is not available
        """
        if self.kb is None:
            raise ValueError("Knowledge base is not available")
        return await self.kb.update_memory(memory_id, value, key)
    
    async def delete_memory(self, memory_id: str) -> bool:
        """
        Delete a memory entry by ID.
        
        Args:
            memory_id: Memory ID to delete
            
        Returns:
            Whether deletion was successful
            
        Raises:
            ValueError: If knowledge base is not available
        """
        if self.kb is None:
            raise ValueError("Knowledge base is not available")
        return await self.kb.delete_memory(memory_id)
    
    async def retrieve_memory(
        self, 
        query: Dict[str, Any], 
        top_k: int = 10
    ) -> List[Dict[str, Any]]:
        """
        Retrieve relevant memories from knowledge base.
        
        Args:
            query: Query dictionary for retrieval
            top_k: Number of results to return
            
        Returns:
            List of candidate memories with relevance scores
            
        Raises:
            ValueError: If knowledge base is not available
        """
        if self.kb is None:
            raise ValueError("Knowledge base is not available")
        return await self.kb.retrieve_memory(query, top_k)
    
    async def operate(self, operation: Dict[str, Any]) -> Tuple[bool, Optional[str]]:
        """
        Execute a KB operation based on operation type.
        
        Supported operation types:
        - 'add' or 'insert': Add new memory
        - 'update' or 'modify': Update existing memory
        - 'delete': Delete memory
        
        Args:
            operation: Operation dictionary with 'type' and relevant fields
            
        Returns:
            (success flag, memory ID or message)
        """
        op_type = operation.get("type")
        
        if op_type in ["add", "insert"]:
            key = operation.get("key", {})
            value = operation.get("content", {})
            return await self.add_memory(key, value)
        
        elif op_type in ["update", "modify"]:
            memory_id = operation.get("id")
            key = operation.get("key", None)
            value = operation.get("content", {})
            success = await self.update_memory(memory_id, value, key)
            return success, memory_id if success else None
        
        elif op_type == "delete":
            memory_id = operation.get("id")
            success = await self.delete_memory(memory_id)
            return success, memory_id if success else None
        
        else:
            raise ValueError(f"Unknown operation type: {op_type}")